def risk_manager(state: StrategistState) -> Dict[str, Any]:
    """
    Risk Manager Agent (STEP 7):
    Applies deterministic hard rules (max_loss <= 15,000, reward/risk >= 1.2, strike validation)
    combined with LLM Greeks / tail-risk analysis. Approves or triggers feedback loop.
    """
    proposal = state.get("quant_proposal", {})
    market_data = state.get("market_data", {})
    revisions = state.get("revision_count", 1)
    timestamp = datetime.now(timezone.utc).isoformat()

    strategy_name = proposal.get("strategy_name", "Option Strategy")
    max_loss = float(proposal.get("max_loss", 99999.0))
    max_profit = float(proposal.get("max_profit", 0.0))
    legs = proposal.get("legs", [])

    logger.info(f"risk_manager: Evaluating {strategy_name} (Max Loss: INR {max_loss:,.2f})")

    # UPGRADE 38: Handle explicit NO_TRADE from quant_analyst
    if str(strategy_name).upper() == "NO_TRADE":
        critique = proposal.get("rationale") or "NO_TRADE proposed by Quant Analyst due to unfavorable risk/reward."
        logger.info(f"[RISK MANAGER] NO_TRADE approved as clean skip: {critique}")
        message = {
            "agent": "Risk Manager",
            "stage": f"Risk Evaluation (#{revisions})",
            "text": f"Risk Manager: Verdict [NO_TRADE_SKIPPED]. {critique}",
            "timestamp": timestamp,
        }
        return {
            "risk_approved": False,
            "risk_feedback": critique,
            "final_trade": {},
            "is_market_state_rejection": True,
            "messages": [message],
        }

    # Deterministic Hard Check 1: Max Loss constraint
    deterministic_passed = True
    is_market_state_rejection = False
    fail_reasons: List[str] = []

    if max_loss > 15000.0:
        deterministic_passed = False
        fail_reasons.append(f"Max Loss INR {max_loss:,.2f} exceeds strict desk cap of INR 15,000.00.")

    # Deterministic Hard Check 2: Reward-to-Risk ratio when finite
    if max_loss > 0 and max_profit > 0:
        rr_ratio = max_profit / max_loss
        if rr_ratio < 0.6 and revisions == 1:
            deterministic_passed = False
            fail_reasons.append(f"Reward-to-risk ratio ({rr_ratio:.2f}) is below optimal desk tolerance.")

    # Deterministic Hard Check 3: Validate strikes against market data
    available_strikes = {s.get("strike", s.get("strikePrice")) for s in market_data.get("strikes", []) if s.get("strike") is not None or s.get("strikePrice") is not None}
    if available_strikes:
        for leg in legs:
            leg_strike = leg.get("strike")
            if leg_strike and leg_strike not in available_strikes and revisions == 1:
                # Warning or soft check
                pass

    # Deterministic Hard Check 4 (STEP 20 & 21): Trend-state alignment guard & Condor delta check
    trend_state = market_data.get("trend_state") or market_data.get("intraday_technicals", {}).get("trend_state", "CHOPPY_SIDEWAYS")
    strat_lower = strategy_name.lower()

    if trend_state == "STRONG_UPTREND":
        if any(w in strat_lower for w in ["condor", "bear", "put spread", "straddle", "strangle"]):
            deterministic_passed = False
            fail_reasons.append(
                f"Trend alignment violation: Strategy '{strategy_name}' rejected because market is in STRONG_UPTREND (neutral/bearish strategies prohibited)."
            )
    elif trend_state == "STRONG_DOWNTREND":
        if any(w in strat_lower for w in ["condor", "bull", "call spread", "straddle", "strangle"]):
            deterministic_passed = False
            fail_reasons.append(
                f"Trend alignment violation: Strategy '{strategy_name}' rejected because market is in STRONG_DOWNTREND (neutral/bullish strategies prohibited)."
            )

    # Deterministic Hard Check 4B (STEP 24): Extreme PCR Regime Protection
    pcr_val = float(market_data.get("pcr", 1.0) or 1.0)
    technicals_info = market_data.get("intraday_technicals", {})
    m5_pts = float(technicals_info.get("move_5m_pts", 0.0) or 0.0)
    ticker_sym = str(state.get("ticker", "NIFTY")).upper()
    pcr_breakout_pts = 85.0 if ticker_sym == "BANKNIFTY" else 35.0

    is_bearish = any(w in strat_lower for w in ["bear", "put spread", "long pe", "pe buy", "bear put"])
    is_bullish = any(w in strat_lower for w in ["bull", "call spread", "long ce", "ce buy", "bull call"])

    if pcr_val >= 1.35 and is_bearish:
        if m5_pts > -pcr_breakout_pts:
            deterministic_passed = False
            fail_reasons.append(
                f"Extreme PCR protection: Strategy '{strategy_name}' rejected because PCR={pcr_val:.2f} >= 1.35 "
                f"(heavy bullish institutional Put writing) without severe breakdown (5m Move: {m5_pts:+.1f} pts > -{pcr_breakout_pts} pts)."
            )

    if pcr_val <= 0.70 and is_bullish:
        if m5_pts < pcr_breakout_pts:
            deterministic_passed = False
            fail_reasons.append(
                f"Extreme PCR protection: Strategy '{strategy_name}' rejected because PCR={pcr_val:.2f} <= 0.70 "
                f"(heavy bearish institutional Call writing) without severe breakout (5m Move: {m5_pts:+.1f} pts < +{pcr_breakout_pts} pts)."
            )

    # Deterministic Hard Check 4C (STEP 26): Enforce Strangle/Straddle Symmetry
    if any(s in strat_lower for s in ["strangle", "straddle"]):
        ce_strikes = [float(l.get("strike", 0)) for l in legs if str(l.get("option_type", l.get("type", ""))).upper() == "CE"]
        pe_strikes = [float(l.get("strike", 0)) for l in legs if str(l.get("option_type", l.get("type", ""))).upper() == "PE"]
        spot_val = float(market_data.get("spot_price", 0.0) or 0.0)
        strike_step = 100.0 if ticker_sym == "BANKNIFTY" else 50.0

        if ce_strikes and pe_strikes and spot_val > 0:
            ce_dist = abs(ce_strikes[0] - spot_val)
            pe_dist = abs(pe_strikes[0] - spot_val)
            dist_diff = abs(ce_dist - pe_dist)
            if dist_diff > 1.5 * strike_step:
                deterministic_passed = False
                fail_reasons.append(
                    "Lopsided strikes detected. A neutral strangle/straddle must use equidistant strikes from the spot price."
                )

    # Deterministic Hard Check 4D (STEP 26): Time-to-EOD Late-Day Debit Strangle/Straddle Protection
    minutes_to_eod_val = float(market_data.get("minutes_to_eod", 999.0) if market_data.get("minutes_to_eod") is not None else 999.0)
    if minutes_to_eod_val < 120:
        if any(w in strat_lower for w in ["strangle", "straddle"]):
            deterministic_passed = False
            fail_reasons.append(
                f"EOD Time Constraint: Only {minutes_to_eod_val:.0f} mins to 15:15 square-off. Long Strangle/Straddle prohibited due to terminal theta decay."
            )

    # Reject any Iron Condor where a short leg has abs(delta) > 0.25 (verified against expanded 15-strike table)
    all_strikes_map = market_data.get("all_strikes_map", {})
    strikes_list = market_data.get("strikes", [])
    strikes_by_num = {s.get("strike"): s for s in strikes_list}

    if "condor" in strat_lower:
        for leg in legs:
            if leg.get("action", "").upper() == "SELL":
                leg_strike = leg.get("strike")
                op_type = leg.get("option_type", "CE").upper()
                delta_val = abs(float(leg.get("delta", 0.0) or 0.0))
                if delta_val == 0.0 and leg_strike and int(leg_strike) in all_strikes_map:
                    delta_val = abs(float(all_strikes_map[int(leg_strike)].get(f"{op_type.lower()}_delta", 0.0)))
                elif delta_val == 0.0 and leg_strike in strikes_by_num:
                    delta_val = abs(float(strikes_by_num[leg_strike].get(f"{op_type.lower()}_delta", 0.0)))

                if delta_val > 0.25:
                    deterministic_passed = False
                    fail_reasons.append(
                        f"Condor delta risk: Short leg at strike {leg.get('strike')} has abs(delta)={delta_val:.2f} > 0.25 limit."
                    )

    # Deterministic Hard Check 5 (STEP 27): Real Order-Book Absolute Bid-Ask Spread Liquidity Check
    for leg in legs:
        leg_strike = leg.get("strike")
        op_type = leg.get("option_type", "CE").upper()
        raw_llm_ltp = float(leg.get("ltp", leg.get("premium", 0.0)))

        strike_info = all_strikes_map.get(int(leg_strike)) if (all_strikes_map and leg_strike) else None
        if not strike_info and leg_strike in strikes_by_num:
            strike_info = strikes_by_num[leg_strike]

        if strike_info:
            if op_type == "CE":
                leg_bid = float(strike_info.get("ce_bid", 0.0) or strike_info.get("bidprice", 0.0) or 0.0)
                leg_ask = float(strike_info.get("ce_ask", 0.0) or strike_info.get("askPrice", 0.0) or 0.0)
                real_ltp = float(strike_info.get("ce_ltp", 0.0) or strike_info.get("ltp", 0.0) or raw_llm_ltp)
            else:
                leg_bid = float(strike_info.get("pe_bid", 0.0) or strike_info.get("bidprice", 0.0) or 0.0)
                leg_ask = float(strike_info.get("pe_ask", 0.0) or strike_info.get("askPrice", 0.0) or 0.0)
                real_ltp = float(strike_info.get("pe_ltp", 0.0) or strike_info.get("ltp", 0.0) or raw_llm_ltp)
            leg_ltp = real_ltp if real_ltp > 0 else raw_llm_ltp
        else:
            leg_bid = float(leg.get("bid", leg.get("bidprice", 0.0)))
            leg_ask = float(leg.get("ask", leg.get("askPrice", 0.0)))
            leg_ltp = raw_llm_ltp

        if leg_ask > 0 and leg_bid > 0:
            if abs(leg_ask - leg_bid) / max(1.0, leg_ltp) > 0.08:
                deterministic_passed = False
                fail_reasons.append(
                    "Illiquid strike selected (bid-ask spread > 8%). Select a more liquid strike."
                )
                break

    # Deterministic Hard Check 6 & 7 (UPGRADE 31): Strict Regime, EMA & Time-of-Day Gatekeeper
    from risk_manager import validate_strict_regime_gatekeeper
    gatekeeper_ok, gatekeeper_reason = validate_strict_regime_gatekeeper(
        ticker=ticker_sym,
        strategy_name=strategy_name,
        market_data=market_data,
        market_bias=proposal.get("market_bias", ""),
    )
    if not gatekeeper_ok and gatekeeper_reason:
        deterministic_passed = False
        fail_reasons.append(gatekeeper_reason)
        is_market_state_rejection = True

    ist_tz = timezone(timedelta(hours=5, minutes=30))
    now_ist = datetime.now(timezone.utc).astimezone(ist_tz)
    current_date_str = now_ist.strftime("%Y-%m-%d")
    current_ist_time = market_data.get("current_ist_time") or now_ist.strftime("%H:%M")
    expiry = market_data.get("nearest_expiry", "N/A")

    dte = 0
    try:
        if expiry and expiry not in ("N/A", "Current Expiry"):
            for fmt in ("%d-%b-%Y", "%Y-%m-%d", "%d-%m-%Y"):
                try:
                    exp_dt = datetime.strptime(expiry, fmt).date()
                    dte = max(0, (exp_dt - now_ist.date()).days)
                    break
                except Exception:
                    pass
    except Exception:
        dte = 0

    # Deterministic Hard Check 8 (UPGRADE 34): Strict Leg-Delta Bounds & Strike Width
    from execution import validate_spread_structure, get_position_bias
    is_valid_struct, struct_msg = validate_spread_structure(ticker_sym, legs, strategy_name)
    if not is_valid_struct:
        deterministic_passed = False
        fail_reasons.append(struct_msg)

    # Deterministic Hard Check 9 (UPGRADE 50 Rule 4): Cross-Index Directional Conflict Guard (Preemption Deleted)
    try:
        from database import engine as db_engine, Position
        from sqlmodel import Session as DBSession, select as db_select
        with DBSession(db_engine) as db_sess:
            all_open = db_sess.exec(db_select(Position).where(Position.status == "OPEN")).all()
            my_bias = get_position_bias(strategy_name, proposal.get("market_bias", ""), legs)

            for op in all_open:
                if op.ticker.upper() != ticker_sym:
                    op_bias = get_position_bias(op.strategy_name)
                    if (my_bias == "BULLISH" and op_bias == "BEARISH") or (my_bias == "BEARISH" and op_bias == "BULLISH"):
                        deterministic_passed = False
                        fail_reasons.append(
                            f"Cross-index directional conflict: Strategy bias '{my_bias}' opposes active "
                            f"position #{op.id} on {op.ticker} ({op.strategy_name}, {op_bias}). Skipping new trade without preemption."
                        )
                        break
    except Exception as exc:
        logger.debug(f"Cross-index conflict check in risk_manager skipped: {exc}")

    # Deterministic Hard Check 10 (UPGRADE 50 Rule 1): Trading Window (09:45-14:45 IST)
    force_mkt_open = os.getenv("FORCE_MARKET_OPEN", "").strip().lower() in ("true", "1", "yes")
    if not force_mkt_open:
        t_ist = (now_ist.hour, now_ist.minute)
        if t_ist < (9, 45):
            deterministic_passed = False
            fail_reasons.append(
                f"Trading Window Restriction: Current time is {now_ist.strftime('%H:%M')} IST. "
                f"New trade entries blocked before 09:45:00 IST to let the 30-minute opening range settle."
            )
        elif t_ist >= (14, 45):
            deterministic_passed = False
            fail_reasons.append(
                f"Trading Window Restriction: Current time is {now_ist.strftime('%H:%M')} IST. "
                f"New entries prohibited past 14:45 IST to prevent late-day theta traps."
            )

    # Deterministic Hard Check 11 (UPGRADE 50 Rule 1): 20-min Cooldown & Daily Limit Caps
    try:
        from autopilot import check_symbol_cooldown_and_exhaustion
        cand_bias = get_position_bias(strategy_name, proposal.get("market_bias", ""), legs)
        spot_val = None
        if isinstance(market_data, dict):
            spot_val = market_data.get("spot_price")
        cool_ok, cool_reason = check_symbol_cooldown_and_exhaustion(
            ticker_sym, proposed_direction=cand_bias, current_spot=spot_val
        )
        if not cool_ok and cool_reason:
            deterministic_passed = False
            fail_reasons.append(cool_reason)
    except Exception as exc:
        logger.debug(f"Exhaustion cooldown check in risk_manager skipped: {exc}")

    try:
        from risk_manager import validate_daily_trade_limits
        daily_ok, daily_reason = validate_daily_trade_limits(ticker_sym)
        if not daily_ok and daily_reason:
            deterministic_passed = False
            fail_reasons.append(daily_reason)
    except Exception as exc:
        logger.debug(f"Daily trade limit check in risk_manager skipped: {exc}")

    # Deterministic Fast-Path Auto-Approval (UPGRADE 32 & 34)
    # If deterministic Python checks pass (Capital Locked <= ₹15,000, Long Delta in [0.38, 0.55],
    # Short Delta in [0.15, 0.30], Net Delta >= 0.19, and Strike Width valid), auto-approve immediately
    # WITHOUT calling the Groq LLM. Eliminates hallucinated rejections and cuts Groq token usage by 50%.
    if deterministic_passed:
        approved = True
        verdict_str = "APPROVED"
        critique = (
            f"Deterministic Fast-Path Approved (Upgrade 34): Capital locked INR {max_loss:,.2f} <= INR 15,000. "
            f"Spread structure, delta bounds [0.38-0.55 / 0.15-0.30], net delta >= 0.19, and strike width validated."
        )
        logger.info(f"[RISK MANAGER FAST-PATH] Auto-approved {strategy_name} for {ticker_sym} without LLM call.")
    elif revisions >= 2:
        # Pass #2 failed risk checks: abort trade instead of force-executing
        approved = False
        verdict_str = "REJECTED (MAX REVISIONS REACHED)"
        critique = (
            " | ".join(fail_reasons)
            if fail_reasons
            else "Max revisions (2) reached without passing risk checks. Aborting trade."
        )
        logger.warning(
            f"[RISK MANAGER] Max revisions (2) reached without passing risk checks. Aborting trade."
        )
    else:
        approved = False
        verdict_str = "REJECTED"
        critique = (
            " | ".join(fail_reasons)
            if fail_reasons
            else "Deterministic risk checks failed. Revise strategy parameters."
        )
        logger.info(f"[RISK MANAGER] Rejected {strategy_name} for {ticker_sym}: {critique}")

    final_trade_payload = {}
    if approved:
        final_trade_payload = {
            **proposal,
            "approved_at": timestamp,
            "risk_assessment": critique,
            "verdict": verdict_str,
            "spot_price": market_data.get("spot_price"),
            "ticker": state.get("ticker", "NIFTY"),
            "expiry": market_data.get("nearest_expiry"),
        }

    log_text = f"Risk Manager: Verdict [{verdict_str}]. Assessment: {critique}"

    message = {
        "agent": "Risk Manager",
        "stage": f"Risk Evaluation (#{revisions})",
        "text": log_text,
        "timestamp": timestamp,
    }

    return {
        "risk_approved": approved,
        "risk_feedback": critique if not approved else "",
        "final_trade": final_trade_payload,
        "is_market_state_rejection": is_market_state_rejection,
        "messages": [message],
    }


