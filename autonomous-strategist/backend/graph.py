def data_engineer(state: StrategistState) -> Dict[str, Any]:
    """
    Data Engineer Agent (STEP 5):
    Fetches real-time NSE options chain data, exact Black-Scholes Greeks,
    Put-Call Ratio (PCR), and historical volatility metrics via yfinance.
    """
    ticker = state.get("ticker", "NIFTY").upper()
    timestamp = datetime.now(timezone.utc).isoformat()
    logger.info(f"[{ticker}] data_engineer: Ingesting live options data and calculating Greeks...")

    live_data = fetch_live_options_data(ticker)

    spot = live_data.get("spot_price", 0.0)
    pcr = live_data.get("pcr", 1.0)
    atm_iv = live_data.get("atm_iv", 15.0)
    expiry = live_data.get("nearest_expiry", "N/A")
    ret_5d = live_data.get("recent_5d_return_pct", 0.0)

    log_text = (
        f"Data Engineer: Ingested live NSE market data for {ticker}. "
        f"Spot: INR {spot:,.2f} | Nearest Expiry: {expiry} | PCR: {pcr:.2f} | "
        f"ATM IV: {atm_iv:.1f}% | 5-Day Return: {ret_5d:+.2f}%. "
        f"Calculated exact Black-Scholes Delta, Gamma, Theta, and Vega across 5 nearest strikes."
    )

    message = {
        "agent": "Data Engineer",
        "stage": "Live Data Ingestion",
        "text": log_text,
        "timestamp": timestamp,
    }

    return {
        "market_data": live_data,
        "messages": [message],
    }


