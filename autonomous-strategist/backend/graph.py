class QuantProposal(BaseModel):
    """Derivatives strategy proposal generated by the Quantitative Analyst."""
    strategy_name: str = Field(description="e.g., Bull Call Spread, Bear Put Spread, NO_TRADE")
    market_bias: str = Field(default="Neutral", description="Bullish, Bearish, Neutral, or Volatile")
    legs: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of option legs: action (BUY/SELL), option_type (CE/PE), strike (int), expiry (str), ltp (float), delta (float)"
    )
    entry_price_net: float = Field(default=0.0, description="Net debit or net credit per share/index point")
    max_profit: float = Field(default=0.0, description="STRICTLY A FLOAT. Do not use strings. If profit is unlimited, output 999999.0")
    max_loss: float = Field(default=0.0, description="STRICTLY A FLOAT. Do not use strings.")
    stop_loss: float = Field(default=0.0, description="Suggested stop loss level or exit condition")
    target: float = Field(default=0.0, description="Suggested target profit level or exit condition")
    rationale: str = Field(default="", description="Quantitative and technical justification for the setup")
    conviction_tier: Optional[str] = Field(default=None, description="HIGH_CONVICTION or SCOUT_PROBE (Upgrade 38)")


class RiskEvaluation(BaseModel):
    """Risk assessment verdict generated by the Risk Manager."""
    approved: bool = Field(description="True if strategy passes all risk constraints, False otherwise")
    risk_score: int = Field(..., description="STRICTLY AN INTEGER between 1 and 10. NO decimals (e.g., use 7, never 7.5).")
    critique: str = Field(description="Detailed feedback if rejected, or approval endorsement if approved")


