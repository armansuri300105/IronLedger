# 3. LLM Client Factory (Groq with Gemini Fallback)
# ---------------------------------------------------------------------------
def get_llm_client(temperature: float = 0.2):
    """
    Instantiates ChatGoogleGenerativeAI if GOOGLE_API_KEY / GEMINI_API_KEY is available.
    Falls back to ChatGroq if GROQ_API_KEY is present.
    Returns None if no API keys are present (enabling graceful deterministic fallback).
    """
    # Primary: Google Gemini (Gemini 2.5 Flash)
    gemini_key = os.getenv("GOOGLE_API_KEY") or os.getenv("GEMINI_API_KEY")
    if gemini_key and gemini_key != "your_gemini_api_key_here":
        try:
            from langchain_google_genai import ChatGoogleGenerativeAI
            return ChatGoogleGenerativeAI(
                model=os.getenv("GEMINI_MODEL", "gemini-2.5-flash"),
                temperature=temperature,
                api_key=gemini_key,
            )
        except Exception as e:
            logger.warning(f"Failed instantiating ChatGoogleGenerativeAI: {e}")

    # Secondary: Groq fallback
    groq_key = os.getenv("GROQ_API_KEY")
    if groq_key and groq_key != "your_groq_api_key_here":
        try:
            from langchain_groq import ChatGroq
            model_name = os.getenv("GROQ_MODEL", "llama-3.1-8b-instant")
            return ChatGroq(
                model=model_name,
                temperature=temperature,
                groq_api_key=groq_key,
            )
        except Exception as e:
            logger.warning(f"Failed instantiating ChatGroq: {e}")

    return None

    return None


