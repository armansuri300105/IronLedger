class StrategistState(TypedDict):
    """
    Central state dictionary for the Autonomous Equity & Options Strategist.
    """
    ticker: str
    messages: Annotated[list, operator.add]
    market_data: dict
    rag_context: str
    quant_proposal: dict
    risk_approved: bool
    final_trade: dict
    revision_count: int
    risk_feedback: str
    past_lessons: str
    execution_details: Optional[dict]


# ---------------------------------------------------------------------------
# 2. Pydantic Models for Structured Output
# ---------------------------------------------------------------------------
class QuantProposal(BaseModel):
    """Derivatives strategy proposal generated by the Quantitative Analyst."""
    strategy_name: str = Field(description="e.g., Bull Call Spread, Iron Condor, Long Straddle")
    market_bias: str = Field(description="Bullish, Bearish, Neutral, or Volatile")
    legs: List[Dict[str, Any]] = Field(
        description="List of option legs: action (BUY/SELL), option_type (CE/PE), strike (int), expiry (str), ltp (float), delta (float)"
    )
    entry_price_net: float = Field(description="Net debit or net credit per share/index point")
    max_profit: float = Field(description="Maximum theoretical profit in INR per lot")
    max_loss: float = Field(description="Maximum theoretical loss in INR per lot")
    stop_loss: float = Field(description="Suggested stop loss level or exit condition")
    target: float = Field(description="Suggested target profit level or exit condition")
    rationale: str = Field(description="Quantitative and technical justification for the setup")


class RiskEvaluation(BaseModel):
    """Risk assessment verdict generated by the Risk Manager."""
    approved: bool = Field(description="True if strategy passes all risk constraints, False otherwise")
    risk_score: int = Field(description="1 to 10 scale, where 10 is highest risk")
    critique: str = Field(description="Detailed feedback if rejected, or approval endorsement if approved")


