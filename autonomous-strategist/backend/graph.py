def route_quant_decision(state: StrategistState) -> str:
    """
    STEP 17: Conditional edge from quant_analyst:
    - If 429 Resource Exhausted occurred, immediately halts and routes to END.
    - Otherwise, proceeds to risk_manager.
    """
    if state.get("rate_limit_exhausted", False):
        logger.warning("[429 RESOURCE EXHAUSTED] Halting LangGraph execution and routing directly to END.")
        return END
    return "risk_manager"


def route_risk_decision(state: StrategistState) -> Literal["quant_analyst", "order_execution_node"]:
    """
    UPGRADE 39 Single-Pass Efficiency:
    - If approved: route to order_execution_node.
    - If rejected on Pass #1 for ANY reason: halt cleanly on Pass #1 without looping to Pass #2,
      routing to order_execution_node so Groq 429 Too Many Requests never occurs.
    """
    is_approved = state.get("risk_approved", False)
    revisions = state.get("revision_count", 0)

    if not is_approved:
        logger.info(
            f"[SINGLE-PASS EFFICIENCY] Trade rejected on Pass #{revisions}. "
            f"Halting revisions cleanly without looping to Pass #2."
        )
        return "order_execution_node"

    logger.info(
        f"Risk checks passed (Approved: {is_approved}, Revisions: {revisions}) -> "
        f"Routing to order_execution_node"
    )
    return "order_execution_node"


def build_graph():
    """Builds and compiles the StateGraph workflow."""
    workflow = StateGraph(StrategistState)

    workflow.add_node("data_engineer", data_engineer)
    workflow.add_node("rag_researcher", rag_researcher)
    workflow.add_node("quant_analyst", quant_analyst)
    workflow.add_node("risk_manager", risk_manager)
    workflow.add_node("order_execution_node", order_execution_node)

    workflow.add_edge(START, "data_engineer")
    workflow.add_edge("data_engineer", "rag_researcher")
    workflow.add_edge("rag_researcher", "quant_analyst")

    # STEP 17: Conditional edge from quant_analyst (routes to END on 429)
    workflow.add_conditional_edges(
        "quant_analyst",
        route_quant_decision,
        {
            "risk_manager": "risk_manager",
            END: END,
        },
    )

    workflow.add_conditional_edges(
        "risk_manager",
        route_risk_decision,
        {
            "quant_analyst": "quant_analyst",
            "order_execution_node": "order_execution_node",
        },
    )

    workflow.add_edge("order_execution_node", END)

    return workflow.compile()



# Export compiled graph
