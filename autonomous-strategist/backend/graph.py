@retry(
    wait=wait_exponential(multiplier=1, min=4, max=60),
    stop=stop_after_attempt(3),
    reraise=True,
)
def invoke_quant_analyst_llm(structured_llm: Any, system_prompt: str, user_prompt: str) -> QuantProposal:
    """
    Invokes structured LLM with exponential backoff on transient errors (STEP 17):
    Retries up to 3 times with wait_exponential(multiplier=1, min=4, max=60).
    """
    return structured_llm.invoke([
        SystemMessage(content=system_prompt),
        HumanMessage(content=user_prompt),
    ])


