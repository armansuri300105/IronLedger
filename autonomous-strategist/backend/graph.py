# 5. Order Execution Node (STEP 13: Direct Auto-Execution)
# ---------------------------------------------------------------------------
def order_execution_node(state: StrategistState) -> Dict[str, Any]:
    """
    Auto-Execution Engine Node (STEP 13):
    Automatically submits approved orders to the virtual paper trading ledger.
    If rejected, records skip status.
    """
    approved = state.get("risk_approved", False)
    final_trade = state.get("final_trade", {})
    timestamp = datetime.now(timezone.utc).isoformat()

    if approved and final_trade:
        strategy_name = final_trade.get("strategy_name", "Options Setup")
        logger.info(f"order_execution_node: Auto-executing approved strategy '{strategy_name}'...")
        exec_details = execute_paper_order(final_trade)

        fill_price = exec_details.get("net_premium", 0.0)
        pos_id = exec_details.get("position_id", "N/A")
        success = exec_details.get("success", False)

        if success:
            log_text = f"[AUTO-EXECUTION] Order placed automatically on virtual ledger: {strategy_name} at INR {fill_price:,.2f}"
            badge_type = "AUTO_BUY"
        else:
            log_text = f"[AUTO-EXECUTION ERROR] Virtual ledger failed: {exec_details.get('message', 'Unknown margin/ledger error')}"
            badge_type = "RISK_REJECTED"

        message = {
            "agent": "Auto-Execution Engine",
            "stage": "Virtual Ledger Commit",
            "text": log_text,
            "timestamp": timestamp,
            "badge_type": badge_type,
            "execution_details": exec_details,
        }

        return {
            "execution_details": exec_details,
            "messages": [message],
        }
    else:
        critique = state.get("risk_feedback") or "Proposal did not satisfy desk constraints."
        log_text = f"[AUTO-SKIPPED] Risk Manager rejected proposal. No order placed. ({critique})"
        logger.info(f"order_execution_node: Skipped execution -> {log_text}")

        message = {
            "agent": "Auto-Execution Engine",
            "stage": "Execution Skipped",
            "text": log_text,
            "timestamp": timestamp,
            "badge_type": "RISK_REJECTED",
        }

        return {
            "execution_details": {"executed": False, "reason": critique},
            "messages": [message],
        }


# ---------------------------------------------------------------------------
# 6. Conditional Routing & Graph Assembly
# ---------------------------------------------------------------------------
def route_risk_decision(state: StrategistState) -> Literal["quant_analyst", "order_execution_node"]:
    """
    Conditional edge from risk_manager:
    - If rejected and revision_count < 3: route to quant_analyst.
    - If approved OR max revisions reached (revision_count >= 3): route to order_execution_node.
    """
    is_approved = state.get("risk_approved", False)
    revisions = state.get("revision_count", 0)

    if not is_approved and revisions < 3:
        logger.info(f"Risk checks failed -> Routing back to quant_analyst for revision #{revisions + 1}")
        return "quant_analyst"

    logger.info(
        f"Risk checks completed (Approved: {is_approved}, Revisions: {revisions}) -> "
        f"Routing to order_execution_node"
    )
    return "order_execution_node"


def build_graph():
    """Builds and compiles the StateGraph workflow."""
    workflow = StateGraph(StrategistState)

    workflow.add_node("data_engineer", data_engineer)
    workflow.add_node("rag_researcher", rag_researcher)
    workflow.add_node("quant_analyst", quant_analyst)
    workflow.add_node("risk_manager", risk_manager)
    workflow.add_node("order_execution_node", order_execution_node)

    workflow.add_edge(START, "data_engineer")
    workflow.add_edge("data_engineer", "rag_researcher")
    workflow.add_edge("rag_researcher", "quant_analyst")
    workflow.add_edge("quant_analyst", "risk_manager")

    workflow.add_conditional_edges(
        "risk_manager",
        route_risk_decision,
        {
            "quant_analyst": "quant_analyst",
            "order_execution_node": "order_execution_node",
        },
    )

    workflow.add_edge("order_execution_node", END)

    return workflow.compile()



# Export compiled graph
graph = build_graph()


